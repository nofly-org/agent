const guardCommand = async (load, name, refuse, what, f) => {
  const [mod, { strictOnCrash }, emit] = await Promise.all([load(), import('../guard/crash.mjs'), import('../guard/emit.mjs')]);
  return strictOnCrash(mod[name], emit[refuse], what)(f);
};

